<script lang="ts">
	// Slots:
	/** @slot {{}} lead - Allows for an optional leading element, such as an icon. @slot {{}} summary - Provide the interactive summary of each item. @slot {{}} content - Provide the content of each item. @slot {{}} iconClosed - Allows for an optional element when the AccordionItem is closed, such as an icon @slot {{}} iconOpen - Allows for an optional element when the AccordionItem is open, such as an icon */
	// Events:
	// FORWARDED: do not document these, breaks the type definition
	// DISPATCHED: document directly above the definition, like props (ex: paginator)

	import { getContext, untrack } from 'svelte';
	import type { Writable } from 'svelte/store';
	import { dynamicTransition } from '../../internal/transitions.js';
	import type { CssClasses, SvelteEvent, Transition, TransitionParams } from '../../index.js';

	// Types
	type TransitionIn = Transition;
	type TransitionOut = Transition;
	type AccordionItemEvent = {
		toggle: { event?: Event; id: string; panelId: string; open: boolean; autocollapse: boolean };
	};

	// Event Dispatcher

	// Classes
	const cBase = '';
	const cControl = 'text-start w-full flex items-center space-x-4';
	const cControlIcons = 'fill-current w-3 transition-transform duration-[200ms]';
	const cPanel = '';

	// ---

	// ---

	// ---

	// FIXME: this will need to be renamed `regionIcons` in the future

	// Props (transitions)

	interface Props {
		class?: string;
		ontoggle?: ((event: AccordionItemEvent['toggle']) => void) | undefined;
		onclick?: ((event: MouseEvent) => void) | undefined;
		onkeydown?: ((event: KeyboardEvent) => void) | undefined;
		onkeyup?: ((event: KeyboardEvent) => void) | undefined;
		onkeypress?: ((event: KeyboardEvent) => void) | undefined;
		/** Set open by default on load. */
		open?: boolean;
		/** Provide a unique input id. Auto-generated by default */
		id?: any;
		/** Set the auto-collapse mode. */
		autocollapse?: boolean;
		/** The writable store that houses the auto-collapse active item UUID. */
		active?: Writable<string | null>;
		/** Set the disabled state for this item. */
		disabled?: boolean;
		/** Provide classes to set the accordion item padding styles. */
		padding?: CssClasses;
		/** Provide classes to set the accordion item hover styles. */
		hover?: CssClasses;
		/** Provide classes to set the accordion item rounded styles. */
		rounded?: CssClasses;
		/** Provide arbitrary classes to the trigger button region. */
		caretOpen?: CssClasses;
		/** Provide arbitrary classes to content panel region. */
		caretClosed?: CssClasses;
		/** Provide arbitrary classes to the trigger button region. */
		regionControl?: CssClasses;
		/** Provide arbitrary classes to content panel region. */
		regionPanel?: CssClasses;
		/** Provide arbitrary classes default region. */
		regionCaret?: CssClasses;
		/** Enable/Disable transitions */
		transitions?: boolean;
		/** Provide the transition to used on entry. */
		transitionIn?: TransitionIn;
		/** Transition params provided to `transitionIn`. */
		transitionInParams?: TransitionParams<TransitionIn>;
		/** Provide the transition to used on exit. */
		transitionOut?: TransitionOut;
		/** Transition params provided to `transitionOut`. */
		transitionOutParams?: TransitionParams<TransitionOut>;
		lead?: import('svelte').Snippet;
		summary?: import('svelte').Snippet;
		iconClosed?: import('svelte').Snippet;
		iconOpen?: import('svelte').Snippet;
		content?: import('svelte').Snippet;
	}

	let {
		class: className = '',
		ontoggle = undefined,
		onclick = undefined,
		onkeydown = undefined,
		onkeyup = undefined,
		onkeypress = undefined,
		open = $bindable(false),
		id = String(Math.random()),
		autocollapse = getContext<NonNullable<Props['autocollapse']>>('autocollapse'),
		active = getContext<NonNullable<Props['active']>>('active'),
		disabled = getContext<NonNullable<Props['disabled']>>('disabled'),
		padding = getContext<NonNullable<Props['padding']>>('padding'),
		hover = getContext<NonNullable<Props['hover']>>('hover'),
		rounded = getContext<NonNullable<Props['rounded']>>('rounded'),
		caretOpen = getContext<NonNullable<Props['caretOpen']>>('caretOpen'),
		caretClosed = getContext<NonNullable<Props['caretClosed']>>('caretClosed'),
		regionControl = getContext<NonNullable<Props['regionControl']>>('regionControl'),
		regionPanel = getContext<NonNullable<Props['regionPanel']>>('regionPanel'),
		regionCaret = getContext<NonNullable<Props['regionCaret']>>('regionCaret'),
		transitions = getContext<NonNullable<Props['transitions']>>('transitions'),
		transitionIn = getContext<NonNullable<Props['transitionIn']>>('transitionIn'),
		transitionInParams = getContext<NonNullable<Props['transitionInParams']>>('transitionInParams'),
		transitionOut = getContext<NonNullable<Props['transitionOut']>>('transitionOut'),
		transitionOutParams = getContext<NonNullable<Props['transitionOutParams']>>('transitionOutParams'),
		lead,
		summary,
		iconClosed,
		iconOpen,
		content
	}: Props = $props();

	const svgCaretIcon = `
		<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 448 512">
			<path d="M201.4 374.6c12.5 12.5 32.8 12.5 45.3 0l160-160c12.5-12.5 12.5-32.8 0-45.3s-32.8-12.5-45.3 0L224 306.7 86.6 169.4c-12.5-12.5-32.8-12.5-45.3 0s-12.5 32.8 0 45.3l160 160z" />
		</svg>`;

	// Change open behavior based on auto-collapse mode
	function setActive(event?: SvelteEvent<MouseEvent, HTMLButtonElement>): void {
		if (autocollapse === true) {
			// Set item active
			active.set(id);
		} else {
			// Toggle Item on click
			open = !open;
		}
		// Always fire the toggle event
		onToggle(event);
	}

	function onToggle(event?: SvelteEvent<MouseEvent, HTMLButtonElement>): void {
		const currentOpenState = autocollapse ? $active === id : open;
		/** @event {{ event: Event, id: string, panelId: string, open: boolean, autocollapse: boolean }} toggle - Fires when an accordion item is toggled. */
		ontoggle?.({
			event,
			id,
			panelId: `accordion-panel-${id}`,
			open: currentOpenState,
			autocollapse
		});
	}

	// If auto-collapse mode enabled and item is set open, set as this item active
	untrack(() => {
		if (autocollapse && open) setActive();
	});

	// Reactive State
	$effect.pre(() => {
		if (open && autocollapse) untrack(setActive);
	});
	let openState = $derived(autocollapse ? $active === id : open);
	// Reactive Classes
	let classesBase = $derived(`${cBase} ${className ?? ''}`);
	let classesControl = $derived(`${cControl} ${padding} ${hover} ${rounded} ${regionControl}`);
	let classesCaretState = $derived(openState ? caretOpen : caretClosed);
	let classesControlCaret = $derived(`${cControlIcons} ${regionCaret} ${classesCaretState}`);
	let classesControlIcons = $derived(`${cControlIcons} ${regionCaret}`);
	let classesPanel = $derived(`${cPanel} ${padding} ${rounded} ${regionPanel}`);
</script>

<!-- @component The Accordion child element. -->

<div class="accordion-item {classesBase}" data-testid="accordion-item">
	<!-- Control -->
	<button
		type="button"
		class="accordion-control {classesControl}"
		{id}
		onclick={(event) => {
			setActive(event);
			onclick?.(event);
		}}
		onkeydown={(event) => onkeydown?.(event)}
		onkeyup={(event) => onkeyup?.(event)}
		onkeypress={(event) => onkeypress?.(event)}
		aria-expanded={openState}
		aria-controls="accordion-panel-{id}"
		{disabled}
	>
		<!-- Lead -->
		{#if lead}
			<div class="accordion-lead">
				{@render lead?.()}
			</div>
		{/if}
		<!-- Summary -->
		<div class="accordion-summary flex-1">
			{#if summary}{@render summary()}{:else}(summary){/if}
		</div>
		<!-- Icons -->
		{#if iconClosed || iconOpen}
			<!-- Custom -->
			<!-- If a custom icon is provided, do not use rotation -->
			<div class="accordion-summary-icons {classesControlIcons}">
				{#if openState}
					{#if iconClosed}{@render iconClosed()}{:else}{@html svgCaretIcon}{/if}
				{:else}
					{#if iconOpen}{@render iconOpen()}{:else}{@html svgCaretIcon}{/if}
				{/if}
			</div>
		{:else}
			<!-- SVG Caret -->
			<div class="accordion-summary-caret {classesControlCaret}">{@html svgCaretIcon}</div>
		{/if}
	</button>
	<!-- Panel -->
	{#if openState}
		<div
			class="accordion-panel {classesPanel}"
			id="accordion-panel-{id}"
			in:dynamicTransition|local={{ transition: transitionIn, params: transitionInParams, enabled: transitions }}
			out:dynamicTransition|local={{ transition: transitionOut, params: transitionOutParams, enabled: transitions }}
			role="region"
			aria-hidden={!openState}
			aria-labelledby={id}
		>
			{#if content}{@render content()}{:else}(content){/if}
		</div>
	{/if}
</div>
